function icon(name, size = 20) {
  const svg = ICONS[name] || '';
  if (size !== 24 && svg) {
    return svg.replace(/width="24" height="24"/g, `width="${size}" height="${size}"`);
  }
  return svg;
}

// 导航高亮：根据 body[data-page] 自动标记 .active
function initNavActive() {
  const page = document.body.dataset.page;
  document.querySelectorAll('.nav-items a[data-nav]').forEach(a => {
    if (a.dataset.nav === page) {
      a.classList.add('active');
    }
  });
}

// 渲染导航图标
function renderNavIcons() {
  document.querySelectorAll('.nav-items a[data-nav]').forEach(a => {
    const navKey = a.dataset.nav;
    const iconMap = {
      'dashboard': 'layout-dashboard',
      'members': 'users',
      'owner': 'folder-open',
      'projects': 'list-checks',
      'calculation': 'calculator',
    };
    const iconName = iconMap[navKey];
    if (iconName) {
      a.insertAdjacentHTML('afterbegin', icon(iconName, 20));
    }
  });
}

// Toast 通知
function showToast(message, type = 'success') {
  let toast = document.querySelector('.toast');
  if (!toast) {
    toast = document.createElement('div');
    toast.className = 'toast';
    document.body.appendChild(toast);
  }
  toast.className = `toast ${type}`;
  toast.innerHTML = `${icon(type === 'success' ? 'check-circle' : 'alert-triangle', 18)}<span>${message}</span>`;
  toast.classList.add('show');
  setTimeout(() => toast.classList.remove('show'), 2800);
}

// 计算积分完成率（decimals 控制小数位，默认 1 位）
function calcCompletionRate(completed, target, decimals = 1) {
  if (!target) return (0).toFixed(decimals);
  return (completed / target * 100).toFixed(decimals);
}

// 客户端缓存：各页面通过 API 加载后填充，辅助函数同步读取
const Cache = {
  members: [],
  statusConfig: null,
  priorityConfig: null,

  async warmUp() {
    const [membersRes, statusRes, priorityRes] = await Promise.all([
      API.getMembers(),
      API.getStatusConfig(),
      API.getPriorityConfig()
    ]);
    this.members = membersRes.data || [];
    this.statusConfig = statusRes.data;
    this.priorityConfig = priorityRes.data;
  },

  getMember(id) {
    return this.members.find(m => m.id === id);
  }
};

// 获取状态配置（从缓存读取）
function getStatusConfig(status) {
  const config = Cache.statusConfig || {};
  return config[status] || config.planning || { label: status, color: '#94A3B8', bg: '#F1F5F9', icon: 'clock' };
}

// 获取成员信息（从缓存读取）
function getMember(id) {
  const member = Cache.getMember(id);
  return member || { name: '未知', initials: '?', color: '#94A3B8' };
}

// 格式化日期
function formatDate(dateStr) {
  if (!dateStr) return '—';
  const d = new Date(dateStr);
  return `${d.getMonth() + 1}月${d.getDate()}日`;
}

// 切回本页时自动刷新：清除缓存并重新加载数据（避免看到其他标签页修改前的旧数据）
// 用法：bindAutoRefresh(loadFunction)
function bindAutoRefresh(loader, minIntervalMs = 3000) {
  if (typeof loader !== 'function') return;
  let last = 0;
  document.addEventListener('visibilitychange', () => {
    if (document.visibilityState !== 'visible') return;
    const now = Date.now();
    if (now - last < minIntervalMs) return;
    last = now;
    try { API.clearCache(); } catch (e) { /* ignore */ }
    loader();
  });
}

